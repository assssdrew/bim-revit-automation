def H(t,l=1): d.add_heading(t,l)
def P(t,b=False):
    p=d.add_paragraph(); r=p.add_run(t); r.bold=b; return p
def N(t): d.add_paragraph(t,style='List Number')
def B(t): d.add_paragraph(t,style='List Bullet')
def code(t):
    p=d.add_paragraph(); r=p.add_run(t); r.font.name='Consolas'; r.font.size=Pt(9.5)
def warn(t):
    p=d.add_paragraph(); r=p.add_run('⚠ '+t); r.bold=True; r.font.color.rgb=RGBColor(0xC0,0x00,0x00)
def table(rows,head):
    t=d.add_table(rows=1,cols=len(head)); t.style='Light Grid Accent 1'
    for i,h in enumerate(head): t.rows[0].cells[i].text=h
    for row in rows:
        c=t.add_row().cells
        for i,v in enumerate(row): c[i].text=v
    d.add_paragraph()

